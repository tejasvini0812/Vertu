// Combines every migration and the starting catalogue into supabase/setup_all.sql, so a new Supabase
// project can be set up with one paste into the SQL editor. Run after changing a migration:
//   npm run db:setup-sql
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
const R = new URL('../supabase/', import.meta.url).pathname;
const parts = readdirSync(R + 'migrations').sort().map((f) => `-- ===== ${f}\n${readFileSync(R + 'migrations/' + f, 'utf8')}`);
parts.push(`-- ===== seed.sql\n${readFileSync(R + 'seed.sql', 'utf8')}`);
writeFileSync(
  R + 'setup_all.sql',
  `-- VERTU: complete database setup for a NEW, empty Supabase project.\n-- Paste all of it into Supabase -> SQL Editor -> New query, and press Run. Run it only once.\n-- Generated by scripts/make-setup-sql.mjs; do not edit by hand.\n\n${parts.join('\n\n')}\n`,
);
console.log('wrote supabase/setup_all.sql');
